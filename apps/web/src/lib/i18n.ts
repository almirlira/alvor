type Leaves<T> =
  T extends Record<string, unknown>
    ? {
        [K in keyof T]: T[K] extends string
          ? `${K & string}`
          : `${K & string}.${Leaves<T[K]> & string}`;
      }[keyof T]
    : never;

export type TranslationKey = Leaves<typeof ptBR>;

/**
 * Lookup type-safe por caminho pontuado.
 * Lanca em dev se a chave nao existir (tipo-seguro em build impede isso).
 *
 * Interpolacao: passe `params` para substituir `{chave}` na string.
 * Ex: t('drivePicker.folderSelectedLabel', { nome: 'Vendas' })
 * -> 'Pasta selecionada: Vendas'
 */
export function t(key: TranslationKey, params?: Record<string, string>): string {
  const parts = key.split('.');
  let cur: unknown = ptBR;
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[p];
    } else {
      return key;
    }
  }
  let result = typeof cur === 'string' ? cur : key;
  if (params !== undefined) {
    for (const [k, v] of Object.entries(params)) {
      result = result.replaceAll(`{${k}}`, v);
    }
  }
  return result;
}
